'use strict';

/**
 * Generate an OpenAPI 3.0 specification from the core model.
 */
function generateOpenApiSpec(core) {
  const spec = {
    openapi: '3.0.0',
    info: {
      title: core.name,
      version: '1.0.0',
      description: `API generated by ChadStart for "${core.name}"`,
    },
    paths: {},
    components: {
      schemas: {},
    },
  };

  for (const entity of Object.values(core.entities)) {
    const tag = entity.name;
    const basePath = `/api/${toKebabCase(entity.name)}s`;
    const schema = buildEntitySchema(entity, core.entities);

    spec.components.schemas[entity.name] = schema;
    spec.components.schemas[`${entity.name}Input`] = {
      ...schema,
      properties: Object.fromEntries(
        Object.entries(schema.properties).filter(([k]) => k !== 'id')
      ),
    };

    // Collection endpoints
    spec.paths[basePath] = {
      get: {
        tags: [tag],
        summary: `List all ${entity.name}s`,
        parameters: entity.properties.map((p) => ({
          name: p.name,
          in: 'query',
          required: false,
          schema: { type: 'string' },
          description: `Filter by ${p.name}`,
        })),
        responses: {
          200: {
            description: 'OK',
            content: {
              'application/json': {
                schema: { type: 'array', items: { $ref: `#/components/schemas/${entity.name}` } },
              },
            },
          },
        },
      },
      post: {
        tags: [tag],
        summary: `Create a ${entity.name}`,
        requestBody: {
          required: true,
          content: {
            'application/json': {
              schema: { $ref: `#/components/schemas/${entity.name}Input` },
            },
          },
        },
        responses: {
          201: {
            description: 'Created',
            content: {
              'application/json': { schema: { $ref: `#/components/schemas/${entity.name}` } },
            },
          },
          400: { description: 'Bad Request' },
        },
      },
    };

    // Single item endpoints
    spec.paths[`${basePath}/{id}`] = {
      get: {
        tags: [tag],
        summary: `Get ${entity.name} by id`,
        parameters: [idParam()],
        responses: {
          200: {
            description: 'OK',
            content: {
              'application/json': { schema: { $ref: `#/components/schemas/${entity.name}` } },
            },
          },
          404: { description: 'Not Found' },
        },
      },
      patch: {
        tags: [tag],
        summary: `Update ${entity.name}`,
        parameters: [idParam()],
        requestBody: {
          required: true,
          content: {
            'application/json': {
              schema: { $ref: `#/components/schemas/${entity.name}Input` },
            },
          },
        },
        responses: {
          200: {
            description: 'OK',
            content: {
              'application/json': { schema: { $ref: `#/components/schemas/${entity.name}` } },
            },
          },
          404: { description: 'Not Found' },
        },
      },
      delete: {
        tags: [tag],
        summary: `Delete ${entity.name}`,
        parameters: [idParam()],
        responses: {
          200: { description: 'Deleted' },
          404: { description: 'Not Found' },
        },
      },
    };
  }

  // File storage endpoints
  for (const [bucketName, bucketDef] of Object.entries(core.files)) {
    const uploadPath = `/files/${bucketName}`;
    spec.paths[uploadPath] = {
      post: {
        tags: ['Files'],
        summary: `Upload file to ${bucketName}`,
        requestBody: {
          required: true,
          content: { 'multipart/form-data': { schema: { type: 'object', properties: { file: { type: 'string', format: 'binary' } } } } },
        },
        responses: { 200: { description: 'Uploaded' } },
      },
    };
    spec.paths[`${uploadPath}/{file}`] = {
      get: {
        tags: ['Files'],
        summary: `Download file from ${bucketName}`,
        parameters: [{ name: 'file', in: 'path', required: true, schema: { type: 'string' } }],
        responses: { 200: { description: 'File content' }, 404: { description: 'Not Found' } },
      },
    };
  }

  return spec;
}

function buildEntitySchema(entity, allEntities) {
  const properties = { id: { type: 'integer', readOnly: true } };

  for (const prop of entity.properties) {
    properties[prop.name] = { type: openApiType(prop.type) };
  }

  for (const rel of entity.belongsTo) {
    const relName = typeof rel === 'string' ? rel : rel;
    const refEntity = allEntities[relName];
    if (refEntity) {
      properties[`${refEntity.tableName}_id`] = { type: 'integer' };
    }
  }

  return { type: 'object', properties };
}

function openApiType(sqlType) {
  const map = {
    text: 'string',
    string: 'string',
    integer: 'integer',
    int: 'integer',
    number: 'number',
    float: 'number',
    real: 'number',
    boolean: 'boolean',
    bool: 'boolean',
    date: 'string',
    json: 'string',
  };
  return map[sqlType] || 'string';
}

function idParam() {
  return { name: 'id', in: 'path', required: true, schema: { type: 'integer' } };
}

function toKebabCase(str) {
  return str
    .replace(/([A-Z])/g, (m, p, offset) => (offset > 0 ? '-' : '') + p.toLowerCase())
    .replace(/^-/, '');
}

module.exports = { generateOpenApiSpec };
